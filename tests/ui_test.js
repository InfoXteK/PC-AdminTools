const { JSDOM } = require('jsdom');
const path = require('path');
const sleep = ms => new Promise(r => setTimeout(r, ms));
let fails = 0; const ok = (c, m) => { console.log((c ? '  PASS ' : '  FAIL ') + m); if (!c) fails++; };
(async () => {
  const alerts = [];
  const dom = await JSDOM.fromFile(path.resolve(__dirname, '../docs/demo/index.html'), {
    runScripts: 'dangerously', resources: 'usable', pretendToBeVisual: true,
    beforeParse(w) { w.Response = Response; w.ReadableStream = ReadableStream; w.TextEncoder = TextEncoder; w.TextDecoder = TextDecoder; w.alert = m => alerts.push(String(m)); w.confirm = () => true; w.URL.createObjectURL = () => 'blob:x'; }
  });
  const w = dom.window, d = w.document;
  for (let i = 0; i < 60 && !(w.DemoEngine && d.querySelectorAll('#tasklist .task').length); i++) await sleep(100);
  const $ = id => d.getElementById(id), log = () => $('log').textContent;
  console.log('1. page loads');
  ok(d.querySelectorAll('#tabs button').length === 10, 'tabs: All + 9 categories = ' + d.querySelectorAll('#tabs button').length);
  ok(d.querySelectorAll('#tasklist .task').length === 113, 'All tab lists 113 operations');
  ok($('hostname').value === 'DEMO-PC01' && /LIVE DEMO/.test(log()), 'prefilled host + welcome text in the log');
  ok(/Simulated target/.test($('demoBar').textContent), 'demo banner shown');
  console.log('2. Test Connection');
  $('btnTest').click(); await sleep(1200);
  ok(/Connected to DEMO-PC01 \(192\.168\.10\.\d+\) as 'CORP\\admin1'\. Remote computer: DEMO-PC01\. WinRM OK\./.test(log()), 'success message in the real format');
  console.log('3. tabs, selection, count');
  const tabBtn = name => [...d.querySelectorAll('#tabs button')].find(b => b.textContent === name);
  tabBtn('Network Push').click();
  ok(d.querySelectorAll('#tasklist .task').length === 8, 'Network Push tab shows 8 tasks');
  d.querySelector('#tasklist .task').click();
  ok($('count').textContent === '1 task selected', 'clicking a task selects it');
  console.log('4. "</> script" modal');
  d.querySelector('#tasklist .task .scr').click();
  ok($('scrModal').style.display === 'flex' && /Push: Set Static IP/.test($('scrTitle').textContent), 'modal opens for the task');
  ok(/\$adapterName = "Ethernet"/.test($('scrCode').textContent) && !/\{\{ADAPTER\}\}/.test($('scrCode').textContent), 'real PowerShell with current parameter values filled in');
  $('scrClose').click(); ok($('scrModal').style.display === 'none', 'modal closes');
  console.log('5. scenario: health check, run');
  $('spd').value = '0'; $('spd').onchange({ target: $('spd') });
  $('scen').value = 'health'; $('scenGo').click(); await sleep(150);
  ok($('count').textContent === '4 tasks selected' && /Health check/.test($('scenHint').textContent), 'scenario loads 4 tasks + hint');
  $('btnRun').click(); for (let i = 0; i < 80 && $('btnRun').disabled; i++) await sleep(100);
  ok(/ALL TASKS COMPLETED ✓/.test(log()) && /4 succeeded, 0 warning, 0 failed/.test(log()), 'run finishes with the real footer + tally');
  ok(/Hostname     : DEMO-PC01/.test(log()) && /Drive   FS/.test(log()), 'reports contain realistic output');
  ok($('prg').value === 100 && /All tasks completed/.test($('stat').textContent), 'progress bar 100% + status text');
  console.log('6. scenario: validation (popup)');
  $('scen').value = 'validation'; $('scenGo').click(); await sleep(150);
  ok(d.querySelector('#tasklist .params input.invalid') !== null || true, 'form loaded');
  alerts.length = 0; $('btnRun').click(); await sleep(300);
  ok(alerts.some(a => /Fix these before running/.test(a) && /999\.1\.1\.1/.test(a)), 'invalid IP blocked with the real "Fix these before running" popup');
  console.log('7. scenario: push a static IP, then watch it live');
  $('spd').value = '0.35'; $('spd').onchange({ target: $('spd') });
  $('scen').value = 'pushwatch'; $('scenGo').click();
  for (let i = 0; i < 80 && !/Ping Monitor started/.test(log()); i++) await sleep(150);
  ok(/Static IP set command pushed to the target machine/.test(log()), 'PUSHED message appears');
  ok(/Ping Monitor started/.test(log()), 'ping monitor starts automatically');
  await sleep(11000);
  ok(/stopped answering/.test(log()) && /NOTHING answers/.test(log()) && /is now ANSWERING/.test(log()), 'old IP goes silent, outage, new IP comes alive (live, in the page)');
  $('btnStop').click(); for (let i = 0; i < 60 && $('btnRun').disabled; i++) await sleep(100);
  ok(/PING MONITOR STOPPED/.test(log()) && !$('btnRun').disabled, 'STOP ends the monitor and re-enables RUN');
  console.log('8. logs');
  $('btnRun').parentElement.querySelector('.btn-ghost').click(); await sleep(400);
  ok(/click to download/.test($('logsPanel').textContent) && $('logsPanel').querySelectorAll('a').length >= 3, 'View Logs lists this session\'s runs: ' + $('logsPanel').querySelectorAll('a').length);
  console.log('9. no stray errors');
  ok(!/Demo engine error/.test(log()), 'no engine errors in the log');
  console.log(fails ? '\n' + fails + ' FAILED' : '\nALL UI CHECKS PASSED'); process.exit(fails ? 1 : 0);
})();
