"""Builds docs/demo/ops-data.js from the REAL app.py so the demo can never drift from the tool.
Usage (from the repo root):  python tools/build_data.py <path-to-app.py> <output-ops-data.js>"""
import importlib.util, json, sys, re, os
src = sys.argv[1]; out = sys.argv[2]
spec = importlib.util.spec_from_file_location("appmod", src)
m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
H = getattr(m, "_PS_NET_HELPERS", "")
ops, scripts = [], {}
for o in m.OPERATIONS:
    meta = {k: o[k] for k in ("id", "label", "category", "description")}
    meta["danger"] = bool(o.get("danger"))
    meta["params"] = o.get("params", [])
    for flag in ("detached", "net_disruptive", "push", "monitor", "needs_cred"):
        if o.get(flag): meta[flag] = True
    if o.get("push_msg"): meta["push_msg"] = o["push_msg"]
    ops.append(meta)
    cmd = o["command"].replace(H, "").strip() if H else o["command"].strip()
    cmd = re.sub(r"\n{3,}", "\n\n", cmd)
    scripts[o["id"]] = cmd
with open(out, "w", encoding="utf-8") as f:
    f.write("/* GENERATED by tools/build_data.py from the real app.py -- do not edit by hand */\n")
    f.write("window.DEMO_OPS = " + json.dumps(ops, ensure_ascii=False) + ";\n")
    f.write("window.DEMO_CATS = " + json.dumps(m.CATEGORIES, ensure_ascii=False) + ";\n")
    f.write("window.DEMO_SCRIPTS = " + json.dumps(scripts, ensure_ascii=False) + ";\n")
    f.write("window.DEMO_META = " + json.dumps({"version": "v4.0", "port": 3030, "count": len(ops)}) + ";\n")
print("ops:", len(ops), "cats:", len(m.CATEGORIES), "bytes:", os.path.getsize(out))
